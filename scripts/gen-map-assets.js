// ── CRT scanline tile (4×4): rows 0-1 clear, rows 2-3 dark ────────
const SCAN_PALETTE = { S: '#00000030' };
const SCAN_GRID = [
  '....',
  '....',
  'SSSS',
  'SSSS',
];

function emit(file, exports) {
  fs.writeFileSync(
    path.join(__dirname, '..', 'src', 'assets', file),
    exports,
  );
  console.log(`src/assets/${file} written`);
}

const poiBody = Object.entries(POI_GRIDS)
  .map(([name, grid]) => {
    const png = encodePng(16, renderGrid(grid, POI_PALETTE));
    return `  ${name}: 'data:image/png;base64,${png.toString('base64')}',`;
  })
  .join('\n');

