#!/usr/bin/env node
/**
 * Generates seamless 16×16 map textures as base64 PNGs for fill-pattern /
 * line-pattern (true 8-bit tiled look, per Pokémon/GBA reference):
 *   tex-grass    — green base with darker grass dots
 *   tex-water    — blue base with white wave dashes
 *   tex-road     — light-gray brick/cobble (offset rows, seamless)
 *   tex-building — cream blocks with darker mortar
 * All motifs keep a ≥2px margin from tile edges so tiling never seams.
 * Output: src/assets/mapTextures.ts
 * Usage: node scripts/gen-map-textures.js
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

function crc32(buf) {
  let c, crc = 0xffffffff;
  for (let n = 0; n < buf.length; n++) {
    c = (crc ^ buf[n]) & 0xff;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    crc = (crc >>> 8) ^ c;
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}
function encodePng(size, pixels) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const raw = Buffer.alloc(size * (size * 4 + 1));
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      pixels[y][x].forEach((v, i) => {
        raw[y * (size * 4 + 1) + 1 + x * 4 + i] = v;
      });
    }
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', zlib.deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
const hex = (h) => [
  parseInt(h.slice(1, 3), 16),
  parseInt(h.slice(3, 5), 16),
  parseInt(h.slice(5, 7), 16),
  255,
];

const SIZE = 16;
function blank(base) {
  return Array.from({ length: SIZE }, () => Array.from({ length: SIZE }, () => hex(base)));
}
function stamp(pixels, color, x, y, w = 2, h = 2) {
  for (let dy = 0; dy < h; dy++) {
    for (let dx = 0; dx < w; dx++) {
      pixels[y + dy][x + dx] = hex(color);
    }
  }
}

// grass: scattered darker/lighter dots on green
const grass = blank('#2fbf3f');
[[3, 2], [12, 4], [7, 7], [2, 10], [13, 12]].forEach(([x, y]) => stamp(grass, '#1f8f2f', x, y));
[[9, 3], [4, 13], [14, 9]].forEach(([x, y]) => stamp(grass, '#45d355', x, y, 1, 1));

// water: blue base with white wave dashes (two staggered rows)
const water = blank('#2858e8');
for (let x = 3; x <= 7; x++) water[4][x] = hex('#a8c4ff');
for (let x = 4; x <= 8; x++) water[5][x] = hex('#f8f8f8');
for (let x = 9; x <= 13; x++) water[12][x] = hex('#a8c4ff');
for (let x = 10; x <= 14; x++) water[13][x] = hex('#f8f8f8');

// road: offset brick — horizontal mortar at y=0/y=8, vertical joints at x=0/x=8
const road = blank('#d8d8d0');
for (let x = 0; x < SIZE; x++) {
  road[0][x] = hex('#a8a8a0');
  road[8][x] = hex('#a8a8a0');
}
for (let y = 1; y < 8; y++) road[y][0] = hex('#a8a8a0');
for (let y = 9; y < SIZE; y++) road[y][8] = hex('#a8a8a0');

// building: cream blocks, darker mortar on an 8px grid
const building = blank('#e8e4d4');
for (let x = 0; x < SIZE; x++) {
  building[0][x] = hex('#b0aa96');
  building[8][x] = hex('#b0aa96');
}
for (let y = 0; y < SIZE; y++) {
  building[y][0] = hex('#b0aa96');
  building[y][8] = hex('#b0aa96');
}

const textures = { grass, water, road, building };
const body = Object.entries(textures)
  .map(([name, px]) => {
    const png = encodePng(SIZE, px);
    return `  'tex-${name}': 'data:image/png;base64,${png.toString('base64')}',`;
  })
  .join('\n');

fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'assets', 'mapTextures.ts'),
  `/**
 * Seamless 16×16 map textures for fill-pattern / line-pattern (true 8-bit
 * tiled look). All motifs keep a margin from tile edges so tiling never
 * seams. Generated by scripts/gen-map-textures.js — do not edit by hand.
 */

export const MAP_TEXTURES = {
${body}
};
`,
);
console.log('src/assets/mapTextures.ts written');
